const DICT: Record<string, Record<keyof typeof en, string>> = { en, cs }

export type TKey = keyof typeof en

export function locale(): string {
	if (typeof navigator === "undefined") return "en"
	const lang = (navigator.language || "en").slice(0, 2).toLowerCase()
	return DICT[lang] ? lang : "en"
}

export function t(key: TKey, vars: Record<string, string | number> = {}): string {
	const s = DICT[locale()][key] ?? en[key] ?? key
	return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : ""))
}

/** Localised label for a Packeta status group. */
export function groupLabel(group: string): string {
	const key = `group_${group}` as TKey
	return key in en ? t(key) : group
}
